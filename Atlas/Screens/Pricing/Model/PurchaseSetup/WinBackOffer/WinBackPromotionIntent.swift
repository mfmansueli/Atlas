import Foundation

/// Whether Apple may promote a win-back offer on the App Store with
/// artwork it makes itself: App Store Connect's `promotionIntent`.
enum WinBackPromotionIntent: String, CaseIterable, Hashable, Sendable {
    case notPromoted = "NOT_PROMOTED"
    case autoGeneratedAssets = "USE_AUTO_GENERATED_ASSETS"

    var title: String {
        switch self {
        case .notPromoted: String(localized: "Only in your app and in Settings")
        case .autoGeneratedAssets: String(localized: "Also on the App Store, with Apple’s artwork")
        }
    }
}
