import Foundation

/// What a win-back offer lets change once it's created: who's eligible,
/// when it runs, its priority and whether Apple promotes it on the App
/// Store (`PATCH /v1/winBackOffers/{id}`).
struct WinBackOfferSettings: Hashable, Sendable {
    var eligibility = WinBackEligibility()
    /// `startDate`: the first day; App Store Connect requires one.
    var startDate: Date
    /// `endDate`: the last day; nil runs until it's ended.
    var endDate: Date?
    var priority = WinBackOfferPriority.normal
    var promotionIntent = WinBackPromotionIntent.notPromoted

    init(
        eligibility: WinBackEligibility = WinBackEligibility(),
        startDate: Date,
        endDate: Date? = nil,
        priority: WinBackOfferPriority = .normal,
        promotionIntent: WinBackPromotionIntent = .notPromoted
    ) {
        self.eligibility = eligibility
        self.startDate = startDate
        self.endDate = endDate
        self.priority = priority
        self.promotionIntent = promotionIntent
    }

    /// From a win-back offer's attributes; nil without a start date.
    init?(attributes: [String: Any]) {
        guard let start = (attributes["startDate"] as? String).flatMap(NewIntroductoryOffer.day(from:)) else { return nil }
        eligibility = WinBackEligibility(attributes: attributes)
        startDate = start
        endDate = (attributes["endDate"] as? String).flatMap(NewIntroductoryOffer.day(from:))
        priority = (attributes["priority"] as? String).flatMap(WinBackOfferPriority.init(rawValue:)) ?? .normal
        promotionIntent = (attributes["promotionIntent"] as? String).flatMap(WinBackPromotionIntent.init(rawValue:)) ?? .notPromoted
    }

    /// The attributes, as a create or an edit sends them.
    var attributes: [String: Any] {
        var attributes = eligibility.attributes
        attributes["startDate"] = NewIntroductoryOffer.dayString(startDate)
        attributes["endDate"] = endDate.map { NewIntroductoryOffer.dayString($0) as Any } ?? NSNull()
        attributes["priority"] = priority.rawValue
        attributes["promotionIntent"] = promotionIntent.rawValue
        return attributes
    }

    /// "From 2026-12-01 until 2027-01-31".
    var datesTitle: String {
        let start = String(localized: "From \(NewIntroductoryOffer.dayString(startDate))")
        guard let endDate else { return start }
        return start + " " + String(localized: "until \(NewIntroductoryOffer.dayString(endDate))")
    }

    /// "Paid 3+ months · left 1–12 months ago · From 2026-12-01 · High priority".
    var summary: String {
        var parts = [eligibility.summary, datesTitle]
        if priority == .high { parts.append(String(localized: "High priority")) }
        if promotionIntent == .autoGeneratedAssets { parts.append(String(localized: "Promoted on the App Store")) }
        return parts.joined(separator: " · ")
    }

    /// What App Store Connect would refuse. `startIsFixed` for an offer
    /// that runs already: its start date stays.
    func problems(today: Date, startIsFixed: Bool = false) -> [SubscriptionOfferProblem] {
        guard !startIsFixed else { return eligibility.problems + endProblems(today: today) }
        return eligibility.problems + SubscriptionOfferRules.dateProblems(start: startDate, end: endDate, today: today)
    }

    private func endProblems(today: Date) -> [SubscriptionOfferProblem] {
        guard let endDate else { return [] }
        let calendar = Calendar.current
        return calendar.startOfDay(for: endDate) <= calendar.startOfDay(for: max(startDate, today)) ? [.endsBeforeStart] : []
    }
}
